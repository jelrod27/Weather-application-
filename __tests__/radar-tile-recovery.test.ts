import { createRadarTileRecovery, type RadarRetryTile } from '@/lib/radar/radar-tile-recovery'

function tile(key = 'frame-a', coordinate: [number, number, number] = [4, 3, 6]): RadarRetryTile {
  return { key, getKey: () => `${key}/${coordinate}`, getTileCoord: () => coordinate, getState: () => 3, load: jest.fn() }
}

describe('radar tile recovery', () => {
  beforeEach(() => jest.useFakeTimers())
  afterEach(() => jest.useRealTimers())

  it('retries a failed tile twice with backoff, then stops and reports unavailable', () => {
    const changes = jest.fn()
    const recovery = createRadarTileRecovery(changes)
    recovery.setContext('frame-a', true, () => true)
    const failed = tile()
    recovery.failed(failed)
    expect(changes).toHaveBeenLastCalledWith('retrying')
    jest.advanceTimersByTime(999)
    expect(failed.load).not.toHaveBeenCalled()
    jest.advanceTimersByTime(1)
    expect(failed.load).toHaveBeenCalledTimes(1)
    recovery.failed(failed)
    jest.advanceTimersByTime(1999)
    expect(failed.load).toHaveBeenCalledTimes(1)
    jest.advanceTimersByTime(1)
    expect(failed.load).toHaveBeenCalledTimes(2)
    recovery.failed(failed)
    expect(changes).toHaveBeenLastCalledWith('unavailable')
    jest.advanceTimersByTime(60_000)
    expect(failed.load).toHaveBeenCalledTimes(2)
    recovery.dispose()
  })

  it('clears a recovered tile without hiding other missing imagery', () => {
    const changes = jest.fn()
    const recovery = createRadarTileRecovery(changes)
    recovery.setContext('frame-a', true, () => true)
    const first = tile()
    const second = tile('frame-a', [4, 4, 6])
    recovery.failed(first)
    recovery.failed(second)
    recovery.loaded(first)
    expect(changes).toHaveBeenLastCalledWith('retrying')
    recovery.loaded(second)
    expect(changes).toHaveBeenLastCalledWith('healthy')
    jest.advanceTimersByTime(5000)
    expect(first.load).not.toHaveBeenCalled()
    expect(second.load).not.toHaveBeenCalled()
    recovery.dispose()
  })

  it('ignores stale frames and cancels retries when hidden, outside the view, or disposed', () => {
    const changes = jest.fn()
    const recovery = createRadarTileRecovery(changes)
    const failed = tile()
    recovery.setContext('frame-a', true, () => true)
    recovery.failed(failed)
    recovery.setContext('frame-b', true, () => true)
    recovery.failed(tile('frame-a', [4, 5, 6]))
    expect(changes).toHaveBeenLastCalledWith('healthy')
    jest.advanceTimersByTime(5000)
    expect(failed.load).not.toHaveBeenCalled()
    recovery.setContext('frame-a', false, () => true)
    jest.advanceTimersByTime(5000)
    expect(failed.load).not.toHaveBeenCalled()
    recovery.setContext('frame-a', true, () => false)
    jest.advanceTimersByTime(5000)
    expect(failed.load).not.toHaveBeenCalled()
    recovery.setContext('frame-a', true, () => true)
    expect(changes).toHaveBeenLastCalledWith('retrying')
    recovery.dispose()
    jest.advanceTimersByTime(5000)
    expect(failed.load).not.toHaveBeenCalled()
    recovery.failed(failed)
    expect(jest.getTimerCount()).toBe(0)
  })

  it('does not replenish an exhausted budget when animation returns to a failed frame', () => {
    const changes = jest.fn()
    const recovery = createRadarTileRecovery(changes)
    recovery.setContext('frame-a', true, () => true)
    const failed = tile()
    recovery.failed(failed)
    jest.advanceTimersByTime(1000)
    recovery.failed(failed)
    jest.advanceTimersByTime(2000)
    recovery.failed(failed)
    recovery.setContext('frame-b', true, () => true)
    recovery.setContext('frame-a', true, () => true)
    expect(changes).toHaveBeenLastCalledWith('unavailable')
    jest.advanceTimersByTime(60_000)
    expect(failed.load).toHaveBeenCalledTimes(2)
    recovery.dispose()
  })

  it('recovers when a cache replacement loads the same logical tile successfully', () => {
    const changes = jest.fn()
    const recovery = createRadarTileRecovery(changes)
    recovery.setContext('frame-a', true, () => true)
    const oldTile = tile()
    recovery.failed(oldTile)
    const replacement = tile()
    recovery.started(replacement)
    recovery.loaded(replacement)
    expect(changes).toHaveBeenLastCalledWith('healthy')
    jest.advanceTimersByTime(5000)
    expect(oldTile.load).not.toHaveBeenCalled()
    recovery.dispose()
  })

  it('retains retry deadlines so fast animation cannot starve recovery', () => {
    const recovery = createRadarTileRecovery(jest.fn())
    recovery.setContext('frame-a', true, () => true)
    const failed = tile()
    recovery.failed(failed)
    jest.advanceTimersByTime(500)
    recovery.setContext('frame-b', true, () => true)
    jest.advanceTimersByTime(6000)
    recovery.setContext('frame-a', true, () => true)
    jest.advanceTimersByTime(1)
    expect(failed.load).toHaveBeenCalledTimes(1)
    recovery.dispose()
  })
})
